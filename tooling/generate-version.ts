import * as fs from 'node:fs';
import * as path from 'node:path';

interface PackageJson {
    version?: string;
}

function main(): void {
    const rootDir = process.cwd();
    const packageJsonPath = path.join(rootDir, 'package.json');
    const outputPath = path.join(rootDir, 'cmd', 'jj-view', 'version.generated.go');

    const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8')) as PackageJson;
    if (!pkg.version) {
        throw new Error('Could not find version in package.json');
    }

    const fileContent = `// Copyright 2026 Google LLC
// SPDX-License-Identifier: Apache-2.0

// Code generated by tooling/generate-version.ts from package.json. DO NOT EDIT.

package main

var version = ${JSON.stringify(pkg.version)}
`;

    if (fs.existsSync(outputPath)) {
        const existing = fs.readFileSync(outputPath, 'utf8');
        if (existing === fileContent) {
            return;
        }
    }

    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, fileContent, 'utf8');
    console.log(`Generated Go version (${pkg.version}) to ${outputPath}`);
}

main();
